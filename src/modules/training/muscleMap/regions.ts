/**
 * Kalethra muscle maps: the stable muscle ids of the 2D anatomy drawings and the muscle group of
 * the exercise library each one belongs to. Pure, no React.
 *
 * Exercise → `primaryMuscles` / `secondaryMuscles` (groups) → highlight → every region of a
 * highlighted group. The exercise data only knows groups, so a group always lights up as a whole
 * (e.g. "back" = trapezius and erector spinae). Regions without a group are drawn for anatomical
 * orientation and are never highlighted – no exercise data names them.
 *
 * Both bodies (male, female) carry exactly these ids; the drawings are generated by
 * `tools/muscle-maps/build.mjs`, the ids in the SVGs are checked against this list in the tests.
 */
import type { FigureMuscle, MuscleHighlight, MuscleLevel } from '@/core/training';

export const MUSCLE_MAP_VARIANTS = ['male', 'female'] as const;
export type MuscleMapVariant = (typeof MUSCLE_MAP_VARIANTS)[number];

export const MUSCLE_MAP_VIEWS = ['front', 'back'] as const;
export type MuscleMapView = (typeof MUSCLE_MAP_VIEWS)[number];

/**
 * Region id → muscle group (`null`: shown, never highlighted). Ids are permanent: never rename or
 * reuse one. Assignment follows the groups' parts in the 3D contract (`MUSCLE_PARTS`): back =
 * trapezius, rhomboids, erector spinae; core = rectus, obliques; forearms = flexors, extensors
 * (with the brachioradialis); glutes = maximus, medius; calves = gastrocnemius, soleus.
 */
export const MUSCLE_REGIONS = {
  'pectoralis-major': 'chest',
  trapezius: 'back',
  'erector-spinae': 'back',
  'latissimus-dorsi': 'lats',
  'deltoid-anterior': 'shoulders',
  'deltoid-lateral': 'shoulders',
  'deltoid-posterior': 'shoulders',
  'biceps-brachii': 'biceps',
  'triceps-brachii': 'triceps',
  brachioradialis: 'forearms',
  'forearm-flexors': 'forearms',
  'forearm-extensors': 'forearms',
  'rectus-abdominis': 'core',
  'external-oblique': 'core',
  'gluteus-maximus': 'glutes',
  'gluteus-medius': 'glutes',
  'rectus-femoris': 'quadriceps',
  'vastus-lateralis': 'quadriceps',
  'vastus-medialis': 'quadriceps',
  'biceps-femoris': 'hamstrings',
  'medial-hamstrings': 'hamstrings',
  adductors: 'adductors',
  'gastrocnemius-medial': 'calves',
  'gastrocnemius-lateral': 'calves',
  soleus: 'calves',
  // Orientation only: no exercise group names these muscles.
  'serratus-anterior': null,
  brachialis: null,
  infraspinatus: null,
  'teres-major': null,
  'tensor-fasciae-latae': null,
  sartorius: null,
  'tibialis-anterior': null,
  'fibularis-longus': null,
} as const satisfies Record<string, FigureMuscle | null>;

export type MuscleRegionId = keyof typeof MUSCLE_REGIONS;

export const MUSCLE_REGION_IDS = Object.keys(MUSCLE_REGIONS) as MuscleRegionId[];

function isRegionId(id: string): id is MuscleRegionId {
  return Object.hasOwn(MUSCLE_REGIONS, id);
}

/** The group of a region id, or `null` for an orientation-only or unknown region. */
export function regionGroup(id: string): FigureMuscle | null {
  return isRegionId(id) ? MUSCLE_REGIONS[id] : null;
}

/** The level a region is shown with, or `null` when it stays neutral. */
export function regionLevel(id: string, highlight: MuscleHighlight): MuscleLevel | null {
  const group = regionGroup(id);
  return group ? (highlight[group] ?? null) : null;
}

/**
 * The drawing with its regions marked: every region of a highlighted group gets
 * `data-level="primary|secondary"`, all others stay as they are. Pure string work on the bundled,
 * trusted SVG; unknown regions are never marked.
 */
export function highlightSvg(svg: string, highlight: MuscleHighlight): string {
  return svg.replace(/data-region="([a-z-]+)"/g, (match, id: string) => {
    const level = regionLevel(id, highlight);
    return level ? `${match} data-level="${level}"` : match;
  });
}
