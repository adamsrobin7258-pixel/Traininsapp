#!/usr/bin/env bash
# Phase 1C: copy of tools/figure-prototype/apk/prepare-android.sh (phase 1A-APK, unchanged) for
# the comparison APK of the branch claude/figure-prototype-stone-1c – same test app "Kalethra
# Figur-Test" (com.kalethra.figureprototype), same edits, only the allowed branch differs.
# Only inside the GitHub Actions workspace of that branch; nothing here is ever committed; the
# Kalethra app's configuration in the repository stays unchanged.
#
# It changes (in the CI workspace only):
#   capacitor.config.ts                         test app id/name, web dir, no native plugins
#   android/app/build.gradle                    applicationId
#   android/app/src/main/res/values/strings.xml label, package name, URL scheme
#   android/app/src/main/AndroidManifest.xml    without camera and Health Connect permissions
#
# Anywhere else – e.g. on your own computer – it stops before touching a file.
set -euo pipefail

BRANCH="claude/figure-prototype-stone-1c"
APP_ID="com.kalethra.figureprototype"
LABEL="Kalethra Figur-Test"

fail() {
  echo "prepare-android: $*" >&2
  exit 1
}

# --- Guard: only the explicitly marked GitHub Actions workspace of this branch ---------------
[[ "${GITHUB_ACTIONS:-}" == "true" && "${CI:-}" == "true" ]] ||
  fail "kein GitHub-Actions-Lauf erkannt – Abbruch, es wurde nichts verändert."
[[ "${KALETHRA_FIGURE_APK:-}" == "ci-workspace" ]] ||
  fail "KALETHRA_FIGURE_APK=ci-workspace fehlt – Abbruch, es wurde nichts verändert."
[[ "${GITHUB_REF:-}" == "refs/heads/${BRANCH}" ]] ||
  fail "falscher Branch (${GITHUB_REF:-unbekannt}) – Abbruch, es wurde nichts verändert."
[[ -n "${GITHUB_WORKSPACE:-}" && -n "${RUNNER_TEMP:-}" ]] ||
  fail "GITHUB_WORKSPACE/RUNNER_TEMP fehlen – Abbruch, es wurde nichts verändert."
[[ "$(pwd -P)" == "$(cd "$GITHUB_WORKSPACE" && pwd -P)" ]] ||
  fail "nicht im Actions-Arbeitsverzeichnis gestartet – Abbruch, es wurde nichts verändert."
[[ -z "$(git status --porcelain --untracked-files=no)" ]] ||
  fail "Arbeitsverzeichnis nicht sauber – Abbruch, es wurde nichts verändert."

GRADLE="android/app/build.gradle"
STRINGS="android/app/src/main/res/values/strings.xml"
MANIFEST="android/app/src/main/AndroidManifest.xml"

# Replaces one exact line (must occur exactly once) – any drift in the files fails loudly.
replace_line() {
  local file="$1" from="$2" to="$3" count
  count=$(grep -cxF -- "$from" "$file" || true)
  [[ "$count" == "1" ]] || fail "$file: erwartete Zeile ${count}x statt 1x gefunden: $from"
  FROM="$from" TO="$to" perl -0pi -e 's/^\Q$ENV{FROM}\E$/$ENV{TO}/m' "$file"
  grep -qxF -- "$to" "$file" || fail "$file: Ersetzung fehlgeschlagen: $to"
}

# --- Capacitor: own id and name, the viewer bundle as web dir, no native plugins --------------
cat > capacitor.config.ts <<EOF
import type { CapacitorConfig } from '@capacitor/cli';

// Generated by tools/figure-prototype/apk/prepare-android.sh in CI – test app only.
const config: CapacitorConfig = {
  appId: '${APP_ID}',
  appName: '${LABEL}',
  webDir: 'dist',
  android: {
    // The viewer uses no native API: no SQLite, camera, health or other plugin in the test app.
    includePlugins: [],
  },
  plugins: {
    SystemBars: { insetsHandling: 'css', initialViewportFitValueHint: 'cover' },
  },
};

export default config;
EOF

# --- Android: application id, label, URL scheme ---------------------------------------------
replace_line "$GRADLE" '        applicationId "com.kalethra.app"' "        applicationId \"${APP_ID}\""
replace_line "$STRINGS" '    <string name="app_name">Kalethra</string>' \
  "    <string name=\"app_name\">${LABEL}</string>"
replace_line "$STRINGS" '    <string name="title_activity_main">Kalethra</string>' \
  "    <string name=\"title_activity_main\">${LABEL}</string>"
replace_line "$STRINGS" '    <string name="package_name">com.kalethra.app</string>' \
  "    <string name=\"package_name\">${APP_ID}</string>"
replace_line "$STRINGS" '    <string name="custom_url_scheme">com.kalethra.app</string>' \
  "    <string name=\"custom_url_scheme\">${APP_ID}</string>"

# --- Manifest: drop camera and Health Connect (the viewer needs neither) ----------------------
perl -ni -e 'print unless /android\.permission\.CAMERA|android\.hardware\.camera|android\.permission\.health\./' "$MANIFEST"
if grep -qE 'android\.permission\.CAMERA|android\.hardware\.camera|android\.permission\.health\.' "$MANIFEST"; then
  fail "$MANIFEST: Kamera- oder Health-Connect-Einträge noch vorhanden"
fi
grep -qF 'android.permission.INTERNET' "$MANIFEST" || fail "$MANIFEST: INTERNET fehlt unerwartet"

echo "prepare-android: Test-App vorbereitet (${APP_ID}, \"${LABEL}\") – nur im CI-Arbeitsverzeichnis."
git status --short
