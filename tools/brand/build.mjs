/**
 * Kalethra brand – writes every vector brand asset from `geometry.mjs` (deterministic, text only):
 *
 *   assets/brand/*.svg                         source artwork (symbol, wordmark, logo, app icon)
 *   src/ui/brand/brandArt.ts                   path data for the app (BrandMark, BrandLogo)
 *   public/favicon.svg                         web favicon
 *   android/…/drawable/ic_kalethra_*.xml       adaptive icon foreground/monochrome, splash icon
 *   android/…/values(-night)/kalethra_brand.xml brand colours for icon and splash
 *
 *   node tools/brand/build.mjs                 write into the project
 *   OUT_ROOT=<dir> node tools/brand/build.mjs  write the same tree elsewhere (tests compare)
 *
 * Raster images for the platforms (launcher PNGs, splash screens, iOS icon) are rendered from the
 * same artwork by `render.mjs`.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SYMBOL_PATH, SYMBOL_SIZE, WORDMARK, WORDMARK_STROKE } from './geometry.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT_ROOT = process.env.OUT_ROOT ?? ROOT;

/** Brand colours – the design tokens `--color-accent-strong` (forest) and `--color-bg` (ivory). */
export const FOREST = '#466a4c';
export const IVORY = '#f3efe6';
/** Dark surface of the app (`--color-bg`, dark theme) for dark splash screens. */
export const NIGHT = '#101612';

const RES = 'android/app/src/main/res';

const svg = (viewBox, body, attrs = '') =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"${attrs}>${body}</svg>\n`;

const symbolPath = (fill) => `<path fill="${fill}" d="${SYMBOL_PATH}"/>`;
const wordmarkPath = (stroke) =>
  `<path fill="none" stroke="${stroke}" stroke-width="${WORDMARK_STROKE}" stroke-linecap="round" stroke-linejoin="round" d="${WORDMARK.d}"/>`;

/** Horizontal logo: symbol, then the wordmark at 36 % of the symbol height, optically aligned. */
function logo(colour) {
  const scale = (SYMBOL_SIZE * 0.36) / WORDMARK.height;
  const gap = 7;
  const [vx, vy] = WORDMARK.viewBox.split(' ').map(Number);
  const x = SYMBOL_SIZE + gap;
  const y = (SYMBOL_SIZE - WORDMARK.height * scale) / 2;
  const width = x + WORDMARK.width * scale;
  return svg(
    `0 0 ${Math.round(width * 100) / 100} ${SYMBOL_SIZE}`,
    `${symbolPath(colour)}<g transform="translate(${Math.round(x * 100) / 100} ${
      Math.round(y * 100) / 100
    }) scale(${Math.round(scale * 10000) / 10000}) translate(${-vx} ${-vy})">${wordmarkPath(
      colour,
    )}</g>`,
  );
}

/** The symbol on a forest square (iOS icon artwork, 1024 px; full bleed, the OS rounds it). */
const appIcon = svg(
  '0 0 1024 1024',
  `<rect width="1024" height="1024" fill="${FOREST}"/><g transform="translate(212 212) scale(12.5)">${symbolPath(
    IVORY,
  )}</g>`,
);

/** Favicon: rounded forest tile, ivory symbol. */
const favicon = svg(
  '0 0 64 64',
  `<rect width="64" height="64" rx="14" fill="${FOREST}"/><g transform="translate(8 8)">${symbolPath(
    IVORY,
  )}</g>`,
);

const vector = (size, viewport, scale, colour) => {
  const offset = (viewport - SYMBOL_SIZE * scale) / 2;
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/brand/build.mjs – do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${size}dp"
    android:height="${size}dp"
    android:viewportWidth="${viewport}"
    android:viewportHeight="${viewport}">
    <group
        android:translateX="${offset}"
        android:translateY="${offset}"
        android:scaleX="${scale}"
        android:scaleY="${scale}">
        <path
            android:fillColor="${colour}"
            android:pathData="${SYMBOL_PATH}" />
    </group>
</vector>
`;
};

const colours = (background, splash) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/brand/build.mjs – Kalethra brand colours. -->
<resources>
    <color name="kalethra_forest">${FOREST}</color>
    <color name="kalethra_ivory">${IVORY}</color>
    <color name="kalethra_icon_background">${background}</color>
    <color name="kalethra_splash_background">${splash}</color>
</resources>
`;

const ts = `/**
 * Kalethra brand artwork for the app – generated by \`tools/brand/build.mjs\` from
 * \`tools/brand/geometry.mjs\` (own drawing). Do not edit by hand.
 */

/** The symbol (abstract figure / "K"), filled, in a ${SYMBOL_SIZE} × ${SYMBOL_SIZE} grid. */
export const SYMBOL_VIEWBOX = '0 0 ${SYMBOL_SIZE} ${SYMBOL_SIZE}';
export const SYMBOL_PATH =
  '${SYMBOL_PATH}';

/** The wordmark "Kalethra", stroked with round ends. */
export const WORDMARK_VIEWBOX = '${WORDMARK.viewBox}';
export const WORDMARK_STROKE = ${WORDMARK_STROKE};
export const WORDMARK_PATH =
  '${WORDMARK.d}';
`;

const files = {
  'assets/brand/kalethra-symbol.svg': svg(`0 0 ${SYMBOL_SIZE} ${SYMBOL_SIZE}`, symbolPath(FOREST)),
  'assets/brand/kalethra-symbol-ivory.svg': svg(
    `0 0 ${SYMBOL_SIZE} ${SYMBOL_SIZE}`,
    symbolPath(IVORY),
  ),
  'assets/brand/kalethra-wordmark.svg': svg(WORDMARK.viewBox, wordmarkPath(FOREST)),
  'assets/brand/kalethra-logo.svg': logo(FOREST),
  'assets/brand/kalethra-logo-ivory.svg': logo(IVORY),
  'assets/brand/kalethra-app-icon.svg': appIcon,
  'public/favicon.svg': favicon,
  'src/ui/brand/brandArt.ts': ts,
  // Adaptive icon (API 26+): 108 dp canvas, the symbol inside the 66 dp safe zone.
  [`${RES}/drawable/ic_kalethra_foreground.xml`]: vector(108, 108, 1.25, IVORY),
  [`${RES}/drawable/ic_kalethra_monochrome.xml`]: vector(108, 108, 1.25, '#FFFFFF'),
  // Android 12+ splash icon: 288 dp canvas without icon background, content well inside the
  // 192 dp circle.
  [`${RES}/drawable/ic_kalethra_splash.xml`]: vector(288, 288, 2.6, FOREST),
  [`${RES}/drawable-night/ic_kalethra_splash.xml`]: vector(288, 288, 2.6, IVORY),
  [`${RES}/values/kalethra_brand.xml`]: colours(FOREST, IVORY),
  [`${RES}/values-night/kalethra_brand.xml`]: colours(FOREST, NIGHT),
};

for (const [path, content] of Object.entries(files)) {
  const file = join(OUT_ROOT, path);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
}
console.log(`wrote ${String(Object.keys(files).length)} files to ${OUT_ROOT}`);
